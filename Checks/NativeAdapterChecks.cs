using System.Buffers.Binary;
using System.IO;
using System.Text;
using HytaleAccounts;

internal static class NativeAdapterChecks
{
    private const string Service = "hytale-launcher/srv/account.(*Service).CheckNetworkMode";
    private const string Controller = "hytale-launcher/srv/account.(*Controller).";
    private const string Auth = "hytale-launcher/internal/auth.(*Controller).Init";
    private const string Capability = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";
    private const string Bootstrap = "<script src=\"http://127.0.0.1:49152/" + Capability + "/ui.js\"></script>";
    private static readonly string[] Hooks = ["window.go.account.Service.CheckNetworkMode", "window.go.account.Service.GenerateOauthURL",
        "window.go.account.Service.IsUserLoggedIn", "window.go.account.Service.LogoutUser", "window.go.account.Service.HasValidSession",
        "launch-game__profile-dropdown", "hy-dropdown__list", "login__container", "settings__action-button", "getUserProfile", "hybutton-split__main"];

    private static int Read32(byte[] bytes, int at) => BinaryPrimitives.ReadInt32LittleEndian(bytes.AsSpan(at, 4));
    private static void Put32(byte[] bytes, int at, int value) => BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(at, 4), value);
    private static void Put64(byte[] bytes, int at, ulong value) => BinaryPrimitives.WriteUInt64LittleEndian(bytes.AsSpan(at, 8), value);
    private static void Write(byte[] bytes, int at, string value) => Encoding.ASCII.GetBytes(value).CopyTo(bytes, at);
    private sealed record Symbol(string Name, int Entry, int Size, int Metadata, int Arguments);

    // Only generated bytes: an inert PE header, Go metadata, ABI wrapper and fake frontend assets.
    private sealed class Fixture
    {
        public readonly byte[] Bytes;
        public readonly int Text, Header, Names, Pc, Table, HtmlAt, StackOffset, UnsafeOffset;
        public readonly Symbol Wrapper, Network, Stop, Init, RunTasks, Load;
        public readonly string Html, ExpectedHtml;
        public Fixture(bool relocated = false)
        {
            Text = relocated ? 0x800 : 0x400;
            var data = Text + 0x1000;
            Header = data + (relocated ? 0x180 : 0x100);
            Names = Header + 0x80; Pc = Header + 0x300; Table = Header + 0x380;
            HtmlAt = data + 0xb00;
            StackOffset = relocated ? 0x57 : 0x11;
            UnsafeOffset = relocated ? 0x09 : 0x2b;
            Bytes = new byte[data + 0x1000];
            Bytes.AsSpan(Text, 0x1000).Fill(0xcc);
            Bytes.AsSpan(data).Fill(0xa5);
            Write(Bytes, 0, "MZ"); Put32(Bytes, 0x3c, 0x80); Write(Bytes, 0x80, "PE\0\0");
            BinaryPrimitives.WriteUInt16LittleEndian(Bytes.AsSpan(0x84), 0x8664); // AMD64
            BinaryPrimitives.WriteUInt16LittleEndian(Bytes.AsSpan(0x86), 2);
            BinaryPrimitives.WriteUInt16LittleEndian(Bytes.AsSpan(0x94), 0xf0);
            BinaryPrimitives.WriteUInt16LittleEndian(Bytes.AsSpan(0x96), 0x22);
            BinaryPrimitives.WriteUInt16LittleEndian(Bytes.AsSpan(0x98), 0x20b); // PE32+
            Put32(Bytes, 0xa8, 0x1000); Put32(Bytes, 0xac, 0x1000);
            Put64(Bytes, 0xb0, 0x140000000); Put32(Bytes, 0xb8, 0x1000); Put32(Bytes, 0xbc, 0x200);
            Put32(Bytes, 0xd0, 0x3000); Put32(Bytes, 0xd4, 0x400);
            BinaryPrimitives.WriteUInt16LittleEndian(Bytes.AsSpan(0xdc), 3);
            Put32(Bytes, 0x104, 16);
            void Section(int at, string name, int rva, int raw, int flags)
            {
                Write(Bytes, at, name); Put32(Bytes, at + 8, 0x1000); Put32(Bytes, at + 12, rva);
                Put32(Bytes, at + 16, 0x1000); Put32(Bytes, at + 20, raw); Put32(Bytes, at + 36, flags);
            }
            Section(0x188, ".text", 0x1000, Text, 0x60000020);
            Section(0x1b0, ".rdata", 0x2000, data, 0x40000040);

            // Relocation changes file offsets, function order/distances, metadata and pc-table offsets independently.
            Wrapper = new(Service, Text + (relocated ? 0x280 : 0x300), 96, Table + 0x100, 32);
            Network = new(Controller + "CheckNetworkMode", Text + (relocated ? 0x4e0 : 0x100), 0x100, Table + 0x140, 32);
            Stop = new(Controller + "Shutdown", Text + (relocated ? 0x3e0 : 0x200), 0x100, Table + 0x180, 8);
            Init = new(Controller + "Init", Text + (relocated ? 0x80 : 0x360), 0x100, Table + 0x1c0, 8);
            RunTasks = new(Controller + "StartUserTasks", Text + (relocated ? 0x2e0 : 0x460), 0x100, Table + 0x200, 8);
            Load = new(Auth, Text + (relocated ? 0x180 : 0x560), relocated ? 0x100 : 0x80, Table + 0x240, 8);
            var symbols = new[] { Wrapper, Network, Stop, Init, RunTasks, Load }.OrderBy(s => s.Entry).ToArray();
            Bytes.AsSpan(Header, 72).Clear();
            Convert.FromHexString("F1FFFFFF00000108").CopyTo(Bytes, Header);
            Put64(Bytes, Header + 8, 6); Put64(Bytes, Header + 24, 0x1000);
            Put64(Bytes, Header + 32, (ulong)(Names - Header)); Put64(Bytes, Header + 56, (ulong)(Pc - Header));
            Put64(Bytes, Header + 64, (ulong)(Table - Header));
            var nameAt = Names;
            for (var i = 0; i < symbols.Length; i++)
            {
                var symbol = symbols[i];
                Put32(Bytes, Table + i * 8, symbol.Entry - Text);
                Put32(Bytes, Table + i * 8 + 4, symbol.Metadata - Table);
                Bytes.AsSpan(symbol.Metadata, 64).Clear();
                Put32(Bytes, symbol.Metadata, symbol.Entry - Text);
                Put32(Bytes, symbol.Metadata + 4, nameAt - Names);
                Put32(Bytes, symbol.Metadata + 8, symbol.Arguments);
                Put32(Bytes, symbol.Metadata + 16, 0x73); Put32(Bytes, symbol.Metadata + 28, 1);
                Put32(Bytes, symbol.Metadata + 44, 0x79);
                Write(Bytes, nameAt, symbol.Name + "\0"); nameAt += symbol.Name.Length + 1;
            }
            Put32(Bytes, Table + symbols.Length * 8, symbols[^1].Entry + symbols[^1].Size - Text);
            new byte[] { 2, 96, 0 }.CopyTo(Bytes, Pc + StackOffset);
            new byte[] { 1, 96, 0 }.CopyTo(Bytes, Pc + UnsafeOffset);
            Convert.FromHexString("493B6610761B554889E54883EC2048894C2440488B00E8000000004883C4205DC34889442408885C241048894C241848897C2420E800000000488B4424080FB65C2410488B4C2418488B7C2420EBB1CCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCC").CopyTo(Bytes, Wrapper.Entry);
            Put32(Bytes, Wrapper.Entry + 23, Network.Entry - (Wrapper.Entry + 27));
            Put32(Bytes, Wrapper.Entry + 53, -0x1234); // Relocatable runtime.morestack call, ignored by the adapter.
            Convert.FromHexString("48894B084889C890E8").CopyTo(Bytes, Init.Entry + 17);
            Put32(Bytes, Init.Entry + 26, Load.Entry - (Init.Entry + 30));
            Write(Bytes, data + 0x800, string.Join('\0', Hooks));
            var assets = $"<script type=\"module\" src=\"/assets/fixture-{(relocated ? "updated" : "original")}.js\"></script><link rel=\"stylesheet\" href=\"/assets/fixture.css\">";
            Html = "<html>\n<head>\n<title>Hytale Launcher</title>\n" + assets +
                "\n<link rel=\"modulepreload\" href=\"/assets/" + new string('p', 200) + ".js\">\n</head>\n<body>\n<div id=\"app\"></div>\n</body>\n</html>";
            ExpectedHtml = "<html><head><title>Hytale Launcher</title>" + assets + "</head><body><div id=\"app\"></div>" + Bootstrap + "</body></html>";
            Write(Bytes, HtmlAt, Html);
        }
    }

    private static void AssertAdapter(Fixture f, byte[] patched, Action<bool, string> check)
    {
        // Decode rel32 instructions against declared fixture symbols, never production-generated expected bytes.
        foreach (var (offset, target, label) in new[] { (54, f.Network.Entry, "network"), (63, f.Stop.Entry, "stop"),
            (72, f.Load.Entry, "load"), (77, f.RunTasks.Entry, "run"), (82, f.Init.Entry, "init") })
        {
            var at = f.Wrapper.Entry + offset;
            check(patched[at] == 0xe9 && at + 5 + Read32(patched, at + 1) == target, "adapter jump destination: " + label);
        }
        foreach (var (offset, target) in new[] { (7, 54), (22, 59), (37, 68), (52, 77), (61, 82) })
            check(f.Wrapper.Entry + offset + 2 + (sbyte)patched[f.Wrapper.Entry + offset + 1] == f.Wrapper.Entry + target,
                "adapter conditional branch destination at " + offset);
        check(patched.AsSpan(f.Wrapper.Entry, 3).SequenceEqual(Convert.FromHexString("488B00")) &&
            patched.AsSpan(f.Wrapper.Entry + 68, 4).SequenceEqual(Convert.FromHexString("488B4008")), "adapter uses service receiver and Controller auth field at +8");
        foreach (var (offset, command) in new[] { (11, "hya:stop"), (26, "hya:load"), (41, "hya:run!") })
            check(Encoding.ASCII.GetString(patched, f.Wrapper.Entry + offset, 8) == command, "adapter command: " + command);
        check(patched.AsSpan(f.Wrapper.Entry + 87, 9).ToArray().All(b => b == 0xcc), "adapter unused wrapper bytes remain traps");
        check(Read32(patched, f.Wrapper.Metadata + 16) == f.StackOffset, "adapter stack pcsp offset is relative to pc table");
        check(Read32(patched, f.Wrapper.Metadata + 44) == f.UnsafeOffset, "adapter unsafe-point offset is relative to pc table");
        check(patched.AsSpan(f.Pc + f.StackOffset, 3).SequenceEqual(new byte[] { 2, 96, 0 }) &&
            patched.AsSpan(f.Pc + f.UnsafeOffset, 3).SequenceEqual(new byte[] { 1, 96, 0 }), "adapter retains constant leaf pc tables");
    }

    private static void AssertPreserved(Fixture f, byte[] patched, bool frontend, Action<bool, string> check)
    {
        check(patched.Length == f.Bytes.Length, "synthetic patch preserves executable length");
        var untouched = (byte[])patched.Clone();
        f.Bytes.AsSpan(f.Wrapper.Entry, 96).CopyTo(untouched.AsSpan(f.Wrapper.Entry));
        foreach (var field in new[] { 16, 44 })
            f.Bytes.AsSpan(f.Wrapper.Metadata + field, 4).CopyTo(untouched.AsSpan(f.Wrapper.Metadata + field));
        if (frontend) f.Bytes.AsSpan(f.HtmlAt, f.Html.Length).CopyTo(untouched.AsSpan(f.HtmlAt));
        check(untouched.SequenceEqual(f.Bytes), "synthetic patch preserves every byte outside the adapter, two metadata fields and optional frontend");
    }

    public static void Run(Action<bool, string> check)
    {
        foreach (var relocated in new[] { false, true })
        {
            var fixture = new Fixture(relocated);
            var direct = (byte[])fixture.Bytes.Clone();
            NativeAdapter.Apply(direct); AssertAdapter(fixture, direct, check); AssertPreserved(fixture, direct, false, check);
            var before = (byte[])fixture.Bytes.Clone();
            var patched = PatchInstaller.PatchCurrent(fixture.Bytes, 49152, Capability);
            check(!ReferenceEquals(patched, fixture.Bytes) && fixture.Bytes.SequenceEqual(before), "PatchCurrent leaves synthetic input untouched (relocated: " + relocated + ")");
            AssertAdapter(fixture, patched, check); AssertPreserved(fixture, patched, true, check);
            check(Encoding.ASCII.GetString(patched, fixture.HtmlAt, fixture.Html.Length) == fixture.ExpectedHtml.PadRight(fixture.Html.Length),
                "PatchCurrent preserves current assets, removes preload/spacing, injects one bootstrap and pads allocation (relocated: " + relocated + ")");
        }

        void Reject(string label, string message, Action<Fixture> change, bool adapter = true)
        {
            foreach (var direct in adapter ? new[] { true, false } : new[] { false })
            {
                var f = new Fixture(); change(f);
                var before = (byte[])f.Bytes.Clone();
                IOException? failure = null;
                try { if (direct) NativeAdapter.Apply(f.Bytes); else PatchInstaller.PatchCurrent(f.Bytes, 49152, Capability); }
                catch (IOException ex) { failure = ex; }
                check(failure?.Message.Contains(message, StringComparison.Ordinal) == true, (direct ? "NativeAdapter" : "PatchCurrent") + " rejects " + label);
                check(f.Bytes.SequenceEqual(before), "rejected " + label + " preserves input bytes");
            }
        }
        Reject("non-x64 image", "Only the Windows x64", f => BinaryPrimitives.WriteUInt16LittleEndian(f.Bytes.AsSpan(0x84), 0x14c));
        Reject("missing Go metadata", "metadata is missing", f => f.Bytes[f.Header] = 0);
        Reject("unordered metadata tables", "Invalid launcher function metadata", f => Put64(f.Bytes, f.Header + 56, 0x80));
        Reject("oversized function table", "Invalid launcher function metadata", f => Put64(f.Bytes, f.Header + 8, 1000001));
        Reject("overflowing metadata offset", "incompatible native account adapter", f => Put64(f.Bytes, f.Header + 64, ulong.MaxValue));
        Reject("name outside names table", "Invalid launcher function name", f => Put32(f.Bytes, f.Wrapper.Metadata + 4, f.Pc - f.Names));
        Reject("unterminated function name", "Unterminated launcher function name", f => f.Bytes.AsSpan(f.Names, f.Pc - f.Names).Fill((byte)'x'));
        Reject("missing account function", "account function is missing", f => f.Bytes[f.Names] = (byte)'x');
        Reject("mismatched function entry", "Invalid launcher function bounds", f => Put32(f.Bytes, f.Wrapper.Metadata, 1));
        Reject("function beyond text", "Invalid launcher function bounds", f => Put32(f.Bytes, f.Table + 6 * 8, 0x1001));
        Reject("changed argument convention", "calling convention changed", f => Put32(f.Bytes, f.Stop.Metadata + 8, 32));
        Reject("changed wrapper size", "wrapper changed size", f => { Put32(f.Bytes, f.Table + 3 * 8, 0x361); Put32(f.Bytes, f.Init.Metadata, 0x361); });
        Reject("changed wrapper opcode", "wrapper changed layout", f => f.Bytes[f.Wrapper.Entry + 22] ^= 1);
        Reject("wrong wrapper call target", "wrapper changed layout", f => Put32(f.Bytes, f.Wrapper.Entry + 23, 0));
        Reject("changed auth receiver field", "receiver layout changed", f => f.Bytes[f.Init.Entry + 20] = 16);
        Reject("wrong auth call target", "receiver layout changed", f => Put32(f.Bytes, f.Init.Entry + 26, 0));
        Reject("missing stack table", "lacks safe leaf metadata", f => f.Bytes[f.Pc + f.StackOffset] = 0);
        Reject("missing unsafe-point table", "lacks safe leaf metadata", f => f.Bytes[f.Pc + f.UnsafeOffset] = 0);
        Reject("missing preemption metadata", "preemption metadata is missing", f => Put32(f.Bytes, f.Wrapper.Metadata + 28, 0));
        foreach (var hook in Hooks)
            Reject("missing frontend hook " + hook, "frontend account interface changed", f =>
            { var at = f.Bytes.AsSpan().IndexOf(Encoding.ASCII.GetBytes(hook)); f.Bytes[at] = (byte)'X'; }, false);
        Reject("ambiguous frontend title", "Ambiguous embedded frontend", f => Write(f.Bytes, f.HtmlAt + f.Html.Length, "<title>Hytale Launcher</title>"), false);
        Reject("missing frontend start", "Missing embedded frontend boundary", f => f.Bytes[f.HtmlAt] = (byte)'X', false);
        Reject("missing frontend end", "Missing embedded frontend boundary", f => f.Bytes[f.HtmlAt + f.Html.Length - 7] = (byte)'X', false);
        Reject("missing body insertion point", "no room for the addon bootstrap", f => Write(f.Bytes, f.HtmlAt, f.Html.Replace("</body>", "</b0dy>")), false);
        Reject("insufficient bootstrap room", "no room for the addon bootstrap", f =>
        {
            f.Bytes.AsSpan(f.HtmlAt, f.Html.Length).Fill((byte)' ');
            Write(f.Bytes, f.HtmlAt, "<html><title>Hytale Launcher</title><body></body></html>");
        }, false);
        foreach (var (port, capability) in new[] { (1023, Capability), (65536, Capability), (49152, "short"), (49152, new string('!', 43)) })
        {
            var f = new Fixture(); var before = (byte[])f.Bytes.Clone();
            IOException? failure = null;
            try { PatchInstaller.PatchCurrent(f.Bytes, port, capability); } catch (IOException ex) { failure = ex; }
            check(failure?.Message == "Invalid bridge bootstrap." && f.Bytes.SequenceEqual(before), "PatchCurrent rejects invalid bootstrap without mutating input");
        }
        try { NativeAdapter.Apply(new Fixture().Bytes[..128]); throw new Exception("Malformed PE accepted"); }
        catch (IOException ex) { check(ex.InnerException is System.BadImageFormatException, "malformed PE is reported as incompatible adapter"); }
    }
}
